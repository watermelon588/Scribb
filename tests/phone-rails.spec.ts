test('desktop unpaired artwork and page strip fit the same image frame',async({page})=>{
 await seedBook(page.request,{title:'Sidebar proof',pages:[{id:'art',src:'/artworks/roses.jpg',layout:'page',title:'Roses'}]})
 await page.setViewportSize({width:1440,height:900})
 await page.goto('/explore')
 const open=page.getByRole('button',{name:'Open Sidebar proof',exact:true})
 await expect(open.locator('.feed-leaf:visible')).toHaveCount(1)
 await open.click()
 await page.locator('.stage-topline').getByRole('button',{name:'Pages',exact:true}).click()
 const thumb=page.getByRole('button',{name:'Page 1',exact:true})
 await expect(thumb.locator('img')).toBeVisible()
 const geometry=await thumb.evaluate(el=>{
  const img=el.querySelector('img')!.getBoundingClientRect(),frame=el.querySelector('.art-image-frame')!.getBoundingClientRect()
  return {left:img.left-frame.left,top:img.top-frame.top,width:img.width-frame.width}
 })
 for(const value of Object.values(geometry))expect(Math.abs(value)).toBeLessThan(1)
})
