import {test,expect} from './fixtures'
const cors={'access-control-allow-origin':'*','access-control-allow-headers':'authorization,content-type','access-control-allow-methods':'GET,POST,OPTIONS'}

test('guest animation loops silently, account opens and legal pages retain appearance on phones',async({page})=>{
 await page.request.post('/api/auth/logout')
 await page.goto('/')
 const film=page.locator('.welcome-film video')
 await expect(page.getByRole('heading',{name:'A little space for what’s on your mind.'})).toBeVisible()
 await expect.poll(()=>film.evaluate((v:HTMLVideoElement)=>!v.paused&&v.loop&&v.muted&&v.playsInline&&v.videoWidth>0)).toBe(true)
 await expect.poll(()=>film.evaluate((v:HTMLVideoElement)=>v.currentTime)).toBeGreaterThan(.1)
 expect((await film.boundingBox())!.width).toBeLessThanOrEqual(520)
 await page.screenshot({path:'.impeccable/review/desktop.png',fullPage:true})
 await page.getByRole('button',{name:'Create an account',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Create your account'})).toBeVisible()
 await page.locator('.account-legal').getByRole('link',{name:'Terms',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Terms of use.'})).toBeVisible()
 await expect(page.locator('dialog')).not.toBeVisible()
 await page.getByRole('button',{name:'Switch to dark theme'}).click()
 await page.getByRole('link',{name:'Privacy',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Your privacy.'})).toBeVisible()
 await page.reload()
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark')
 await page.screenshot({path:'.impeccable/review/privacy-dark-desktop.png',fullPage:true})
 for(const width of [320,390]){
  await page.setViewportSize({width,height:844})
  for(const route of ['/#privacy','/#terms','/']){
   await page.goto(route)
   await expect(page.locator('main h1')).toBeVisible()
   expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
   await page.screenshot({path:`.impeccable/review/${route==='/'?'welcome':route.slice(2)}-dark-${width}.png`,fullPage:true})
  }
 }
 await page.screenshot({path:'.impeccable/review/mobile.png',fullPage:true})
 await page.getByRole('button',{name:'Switch to light theme'}).click()
 await page.emulateMedia({reducedMotion:'reduce'})
 await expect.poll(()=>film.evaluate((v:HTMLVideoElement)=>v.paused)).toBe(true)
 await page.screenshot({path:'.impeccable/review/welcome-light-390.png',fullPage:true})
 await page.getByRole('button',{name:'Play animation'}).click()
 await expect.poll(()=>film.evaluate((v:HTMLVideoElement)=>v.paused)).toBe(false)
})

