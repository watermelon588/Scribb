test('journal save confirms success and a refused verification never claims an email was sent',async({page,context})=>{
 await seedJournal(context.request,'Saved notebook',[])
 await page.goto('/',{waitUntil:'domcontentloaded'})
 await page.getByRole('button',{name:'Journals',exact:true}).click()
 await page.getByRole('button',{name:'Edit Saved notebook',exact:true}).click()
 await page.getByRole('button',{name:'Save journal',exact:true}).click()
 const toast=page.locator('.notification')
 await expect(toast).toContainText('Journal saved successfully.')
 await toast.getByRole('button',{name:'Dismiss notification'}).click()
 await page.getByRole('button',{name:'Settings',exact:true}).click()
 await page.route('**/api/me/email',route=>route.fulfill({status:503,json:{error:{code:'unavailable',message:'Email could not be sent. Please try again.'}}}))
 await page.getByRole('textbox',{name:'Email',exact:true}).fill('artist@example.com')
 await page.getByRole('button',{name:'Verify email',exact:true}).click()
 await expect(toast).toContainText('Email could not be sent. Please try again.')
 await expect(toast).toHaveClass(/notice-error/)
 await toast.getByRole('button',{name:'Dismiss notification'}).click()
 await expect(page.getByRole('button',{name:'Verify email',exact:true})).toBeEnabled()
})

