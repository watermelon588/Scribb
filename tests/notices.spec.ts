import {test,expect,seedBook,seedJournal} from './fixtures'

test('profile and email confirmations are visible and dismissible above Settings',async({page})=>{
 test.setTimeout(60000)
 await page.goto('/',{waitUntil:'domcontentloaded'})
 await page.getByRole('button',{name:'Settings',exact:true}).click()
 await page.getByLabel('Bio',{exact:true}).fill('A little rain, a little ink.')
 await page.getByRole('button',{name:'Save profile',exact:true}).click()
 const toast=page.locator('.notification')
 await expect(toast).toContainText('Profile saved successfully.')
 await toast.getByRole('button',{name:'Dismiss notification'}).click()
 await expect(toast).toHaveCount(0)
 await expect(page.getByRole('heading',{name:'Settings',exact:true})).toBeVisible()
 await page.getByRole('textbox',{name:'Email',exact:true}).fill('artist@example.com')
 await page.getByRole('button',{name:'Verify email',exact:true}).click()
 await expect(toast).toContainText('Verification link sent to artist@example.com')
 await toast.getByRole('button',{name:'Dismiss notification'}).click()
 await expect(toast).toHaveCount(0)
 // Repeating an identical action must create a fresh notification.
 await page.getByRole('button',{name:'Resend verification link',exact:true}).click()
 await expect(toast).toContainText('Verification link sent')
 await page.screenshot({path:'.reference-analysis/notices/settings-email-desktop.png'})
 await page.setViewportSize({width:320,height:844})
 await expect(toast.getByRole('button',{name:'Dismiss notification'})).toBeInViewport()
 expect(await toast.evaluate(el=>el.getBoundingClientRect().right<=innerWidth)).toBe(true)
 await page.screenshot({path:'.reference-analysis/notices/settings-email-320.png'})
 await toast.getByRole('button',{name:'Dismiss notification'}).click()
 await page.getByRole('button',{name:'Close dialog'}).click()
 // Phones have no style switch: choose Editorial on desktop, then narrow the window.
 await page.setViewportSize({width:1440,height:900})
 await page.getByRole('button',{name:'editorial style',exact:true}).click()
 await page.setViewportSize({width:390,height:844})
 await page.getByRole('button',{name:'Switch to dark theme'}).click()
 await page.getByRole('button',{name:'Settings',exact:true}).click()
 await page.getByRole('button',{name:/Profile settings/}).click()
 await page.getByRole('textbox',{name:'Email',exact:true}).fill('artist@example.com')
 await page.getByRole('button',{name:'Resend verification link',exact:true}).click()
 await expect(toast).toContainText('Verification link sent')
 await expect(toast.getByRole('button',{name:'Dismiss notification'})).toBeInViewport()
 await page.screenshot({path:'.reference-analysis/notices/settings-email-editorial-dark-390.png'})
 await toast.getByRole('button',{name:'Dismiss notification'}).click()
})

test('success notices expire and failed saves stay actionable without losing the draft',async({page,context})=>{
 test.setTimeout(45000)
 await seedBook(context.request,{title:'Toast sketchbook',visibility:'private'})
 await page.goto('/',{waitUntil:'domcontentloaded'})
 await page.getByRole('button',{name:'Edit Toast sketchbook',exact:true}).click()
 await page.getByRole('button',{name:'Save sketchbook',exact:true}).click()
 await expect(page.locator('.notification')).toContainText('Sketchbook saved successfully.')
 await expect(page.locator('.notification')).toHaveCount(0,{timeout:11000})
 await page.getByRole('button',{name:'Edit Toast sketchbook',exact:true}).click()
 await page.route('**/api/books/*',route=>route.request().method()==='PUT'?route.fulfill({status:503,json:{error:{code:'unavailable',message:'Please try again.'}}}):route.continue())
 await page.getByRole('button',{name:'Save sketchbook',exact:true}).click()
 await expect(page.locator('.notification')).toContainText('Could not save')
 await page.waitForTimeout(8500)
 await expect(page.locator('.notification')).toContainText('Your draft is still here')
 await expect(page.getByLabel('Sketchbook name')).toHaveValue('Toast sketchbook')
 await page.locator('.notification').getByRole('button',{name:'Dismiss notification'}).click()
 await expect(page.getByRole('button',{name:'Save sketchbook',exact:true})).toBeEnabled()
})

